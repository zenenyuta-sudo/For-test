-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Anime' check (category in ('Anime','Movie','Series')),
  description text default '',
  video_url text not null,
  poster_url text default '',
  created_at timestamptz not null default now()
);
alter table public.projects enable row level security;

-- Everyone can view published projects, including visitors without accounts.
create policy "Anyone can view projects"
on public.projects for select
using (true);

-- Admin-only inserts: replace the UUID with your own Supabase Auth user ID.
-- Find it in Authentication > Users after creating your account.
create policy "Admin can add projects"
on public.projects for insert
to authenticated
with check (auth.uid() = 'REPLACE_WITH_YOUR_USER_UUID'::uuid);

create policy "Admin can update projects"
on public.projects for update
to authenticated
using (auth.uid() = 'REPLACE_WITH_YOUR_USER_UUID'::uuid)
with check (auth.uid() = 'REPLACE_WITH_YOUR_USER_UUID'::uuid);

create policy "Admin can delete projects"
on public.projects for delete
to authenticated
using (auth.uid() = 'REPLACE_WITH_YOUR_USER_UUID'::uuid);
